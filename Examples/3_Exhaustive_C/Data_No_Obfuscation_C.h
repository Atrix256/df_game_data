bool Data_No_Obfuscation_C_LoadFromMemory(void* mem, uint32_t memSize, Data_No_Obfuscation_C_Database* db)
{
    #define MAKE_FOUR_CC(A, B, C, D) \
        ( (uint32_t)(uint8_t)A \
        | ((uint32_t)(uint8_t)B << 8) \
        | ((uint32_t)(uint8_t)C << 16) \
        | ((uint32_t)(uint8_t)D << 24))

    uint32_t memIndex = 0;

    // verify fourcc, and see if we need to do endian swaps
    bool endianSwap = false;
    {
        static const uint32_t fourcc_regular = MAKE_FOUR_CC('D', 'F', 'G', 'D');
        static const uint32_t fourcc_swapped = MAKE_FOUR_CC('D', 'G', 'F', 'D');

        uint32_t fourcc = 0;
        if (!Data_No_Obfuscation_C_Read_U32(&fourcc, mem, &memIndex, memSize, false))
            return false;

        if (fourcc == fourcc_swapped)
            endianSwap = true;
        else if (fourcc != fourcc_regular)
            return false;
    }

    // Read the version number the binary file was made with.
    // Unused now, but can be used for backwards compatibility etc later.
    {
        uint8_t version[3];
        if (!Data_No_Obfuscation_C_Read_U8(&version[0], mem, &memIndex, memSize, endianSwap) ||
            !Data_No_Obfuscation_C_Read_U8(&version[1], mem, &memIndex, memSize, endianSwap) ||
            !Data_No_Obfuscation_C_Read_U8(&version[2], mem, &memIndex, memSize, endianSwap))
        {
            return false;
        }
    }

    // De obfuscate the data
    {
        size_t contentStart = 7; // start after the fourcc and the 3 byte version
        size_t bytesRemaining = memSize - contentStart;
        uint32_t rng = Data_No_Obfuscation_C_pcg_hash(0x1337beef);
        uint8_t* data = &((uint8_t*)mem)[contentStart];
        while (bytesRemaining > 0)
        {
            rng = Data_No_Obfuscation_C_pcg_hash(rng);

            for (size_t i = 0; i < ((bytesRemaining < 4) ? bytesRemaining : 4); ++i)
                data[i] = data[i] ^ ((uint8_t*)&rng)[i];

            data += 4;

            if (bytesRemaining >= 4)
                bytesRemaining -= 4;
            else
                bytesRemaining = 0;
        }
    }

    // Verify that the schema hash in the binary data matches the schema hash this file was made for
    {
        uint64_t hash = 0;
        if (!Data_No_Obfuscation_C_Read_U64(&hash, mem, &memIndex, memSize, endianSwap) || hash != 0x5ab74c26c858a4d8ULL)
            return false;
    }

    // Entry Table
    {
        if (!Data_No_Obfuscation_C_Read_U32(&db->table_Entry_count, mem, &memIndex, memSize, endianSwap))
            return false;

        if (db->table_Entry_count > 0)
        {
            // get char** to LUT and fixup string pointers
            if (memSize - memIndex < db->table_Entry_count * sizeof(uint64_t))
                return false;
            db->table_Entry_names = memIndex;
            Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_Ptr(&db->table_Entry_names, mem, endianSwap);
            for (uint32_t i = 0; i < db->table_Entry_count; ++i)
                Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_Ptr(&((uint64_t*)db->table_Entry_names)[i], mem, endianSwap);
            memIndex += db->table_Entry_count * sizeof(uint64_t);

            // Get a pointer to the first entry in the table
            if (memSize - memIndex < db->table_Entry_count * sizeof(Data_No_Obfuscation_C_Entry))
                return false;
            db->table_Entry = memIndex;
            Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_Ptr(&db->table_Entry, mem, endianSwap);
            memIndex += db->table_Entry_count * sizeof(Data_No_Obfuscation_C_Entry);

            // Do pointer fixup
            for (uint32_t i = 0; i < db->table_Entry_count; ++i)
                Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_Entry(&((Data_No_Obfuscation_C_Entry*)db->table_Entry)[i], mem, endianSwap);
        }
    }

    // People Table
    {
        if (!Data_No_Obfuscation_C_Read_U32(&db->table_People_count, mem, &memIndex, memSize, endianSwap))
            return false;

        if (db->table_People_count > 0)
        {
            // get char** to LUT and fixup string pointers
            if (memSize - memIndex < db->table_People_count * sizeof(uint64_t))
                return false;
            db->table_People_names = memIndex;
            Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_Ptr(&db->table_People_names, mem, endianSwap);
            for (uint32_t i = 0; i < db->table_People_count; ++i)
                Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_Ptr(&((uint64_t*)db->table_People_names)[i], mem, endianSwap);
            memIndex += db->table_People_count * sizeof(uint64_t);

            // Get a pointer to the first entry in the table
            if (memSize - memIndex < db->table_People_count * sizeof(Data_No_Obfuscation_C_People))
                return false;
            db->table_People = memIndex;
            Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_Ptr(&db->table_People, mem, endianSwap);
            memIndex += db->table_People_count * sizeof(Data_No_Obfuscation_C_People);

            // Do pointer fixup
            for (uint32_t i = 0; i < db->table_People_count; ++i)
                Data_No_Obfuscation_C_DoEndianSwapAndPointerFixup_People(&((Data_No_Obfuscation_C_People*)db->table_People)[i], mem, endianSwap);
        }
    }

    return true;
}

bool Data_No_Obfuscation_C_LoadFromFile(const char* fileName, Data_No_Obfuscation_C_Database* db)
{
    FILE* file = NULL;
    fopen_s(&file, fileName, "rb");
    if (!file)
        return false;

    fseek(file, 0, SEEK_END);
    uint32_t fileSize = (uint32_t)ftell(file);

    if (db->ownedMemory)
        free(db->ownedMemory);

    db->ownedMemory = malloc(fileSize);
    fseek(file, 0, SEEK_SET);

    if (fread(db->ownedMemory, fileSize, 1, file) != 1)
        return false;

    fclose(file);

    bool ret = Data_No_Obfuscation_C_LoadFromMemory(db->ownedMemory, fileSize, db);

    // Store the filename for hot reloading
    if (!db->fileName || strcmp(db->fileName, fileName))
    {
        if (db->fileName)
            free(db->fileName);
        db->fileName = malloc(strlen(fileName) + 1);
        strcpy_s(db->fileName, strlen(fileName) + 1, fileName);
    }

    // Get the file time for hot reloading
    struct stat fileStat;
    if (stat(db->fileName, &fileStat) == 0)
        db->fileTime = fileStat.st_mtime;

    return ret;
}

bool Data_No_Obfuscation_C_Tick(Data_No_Obfuscation_C_Database* db)
{
    struct stat fileStat;
    if (db->fileName && stat(db->fileName, &fileStat) == 0 && fileStat.st_mtime > db->fileTime)
    {
        db->fileTime = fileStat.st_mtime;
        Data_No_Obfuscation_C_LoadFromFile(db->fileName, db);
        return true;
    }
    return false;
}
